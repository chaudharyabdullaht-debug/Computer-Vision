def predict_video_action(video_path, sequence_length=48):
    cap = cv2.VideoCapture(video_path)
    frames_keypoints = []

    while cap.isOpened() and len(frames_keypoints) < sequence_length:
        ret, frame = cap.read()
        if not ret:
            break

        # Pose estimation frame by frame
        results = pose_model(frame, verbose=False)

        # Extract primary person keypoints (17 joints x 3 [x, y, conf])
        if results[0].keypoints is not None and len(results[0].keypoints) > 0:
            kp = results[0].keypoints.data[0].cpu().numpy()  # Shape: (17, 3)
        else:
            kp = np.zeros((17, 3))

        frames_keypoints.append(kp)

    cap.release()

    # Zero-padding if sequence length is under 48 frames
    while len(frames_keypoints) < sequence_length:
        frames_keypoints.append(np.zeros((17, 3)))

    # Convert sequence to PyTorch Tensor -> Shape: (1, 48, 17, 3)
    sequence_array = np.array(frames_keypoints, dtype=np.float32)
    input_tensor = torch.tensor(sequence_array).unsqueeze(0).to(device)

    # 2. Run classification
    with torch.no_grad():
        outputs = model(input_tensor)
        probs = torch.softmax(outputs, dim=1)
        pred_class = torch.argmax(probs, dim=1).item()
        confidence = probs[0][pred_class].item() * 100

    classes = ["Non-Violent", "Violent"]
    return classes[pred_class], confidence

