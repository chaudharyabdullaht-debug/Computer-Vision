def process_and_annotate_video(input_video_path, output_video_path, sequence_length=48):
    # 1. Initialize YOLOv8 Pose
    pose_model = YOLO("yolov8n-pose.pt")

    cap = cv2.VideoCapture(input_video_path)
    width = int(cap.get(cv2.CAP_PROP_FRAME_WIDTH))
    height = int(cap.get(cv2.CAP_PROP_FRAME_HEIGHT))
    fps = int(cap.get(cv2.CAP_PROP_FPS)) or 30

    # 2. Setup Video Writer
    fourcc = cv2.VideoWriter_fourcc(*'mp4v')
    out = cv2.VideoWriter(output_video_path, fourcc, fps, (width, height))

    kp_sequence = []
    label = "Analyzing..."
    confidence = 0.0

    print(f"Processing video: {input_video_path}...")

    while cap.isOpened():
        ret, frame = cap.read()
        if not ret:
            break

        # Run pose detection and plot keypoint skeletons
        results = pose_model(frame, verbose=False)
        annotated_frame = results[0].plot()

        # Extract keypoints (17 joints x 3)
        if results[0].keypoints is not None and len(results[0].keypoints) > 0:
            kp = results[0].keypoints.data[0].cpu().numpy()
        else:
            kp = np.zeros((17, 3))

        kp_sequence.append(kp)

        # Maintain a sliding window buffer of the latest 48 frames
        if len(kp_sequence) > sequence_length:
            kp_sequence.pop(0)

        # Run 1D-CNN classification when sequence buffer is filled
        if len(kp_sequence) == sequence_length:
            sequence_array = np.array(kp_sequence, dtype=np.float32)
            input_tensor = torch.tensor(sequence_array).unsqueeze(0).to(device)

            with torch.no_grad():
                outputs = model(input_tensor)
                probs = torch.softmax(outputs, dim=1)
                pred_class = torch.argmax(probs, dim=1).item()
                confidence = probs[0][pred_class].item() * 100

            classes = ["Non-Violent", "Violent"]
            label = classes[pred_class]

        # Render prediction status banner overlay
        banner_color = (0, 0, 255) if label == "Violent" else (0, 255, 0) if label == "Non-Violent" else (255, 255, 255)
        display_text = f"{label} ({confidence:.1f}%)" if label != "Analyzing..." else label

        # Draw translucent background bar
        overlay = annotated_frame.copy()
        cv2.rectangle(overlay, (20, 20), (380, 70), (0, 0, 0), -1)
        cv2.addWeighted(overlay, 0.6, annotated_frame, 0.4, 0, annotated_frame)

        # Draw text label
        cv2.putText(annotated_frame, display_text, (35, 55),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.8, banner_color, 2, cv2.LINE_AA)

        out.write(annotated_frame)

    cap.release()
    out.release()
    print(f" Output successfully exported to: {output_video_path}")

