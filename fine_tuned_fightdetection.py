# 1. Define the ActionClassifier1D architecture
class ActionClassifier1D(nn.Module):
    def __init__(self, num_classes=2):
        super(ActionClassifier1D, self).__init__()
        self.net = nn.Sequential(
            nn.Conv1d(in_channels=51, out_channels=64, kernel_size=3, padding=1),
            nn.BatchNorm1d(64),
            nn.ReLU(),
            nn.MaxPool1d(kernel_size=2),
            nn.Conv1d(in_channels=64, out_channels=128, kernel_size=3, padding=1),
            nn.BatchNorm1d(128),
            nn.ReLU(),
            nn.MaxPool1d(kernel_size=2),
            nn.AdaptiveAvgPool1d(1),
            nn.Flatten(),
            nn.Linear(128, 64),
            nn.ReLU(),
            nn.Dropout(0.5),
            nn.Linear(64, num_classes)
        )

    def forward(self, x):
        if x.dim() == 4:
            b, frames, joints, coords = x.shape
            x = x.view(b, frames, joints * coords).transpose(1, 2)
        return self.net(x)

